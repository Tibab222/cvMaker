export type ResumeLabelKey = keyof typeof i18n.en;

/** Label in the resume language, falling back to English then to the key itself. */
export const resumeLabel = (lang: string, key: string, overrides?: Record<string, Record<string, string>>): string => {
    const fromTemplate = overrides?.[lang]?.[key] ?? overrides?.en?.[key];
    if (fromTemplate !== undefined) return fromTemplate;
    const labels = (i18n as Record<string, Record<string, string>>)[lang] ?? i18n.en;
    return labels[key] ?? (i18n.en as Record<string, string>)[key] ?? key;
};
